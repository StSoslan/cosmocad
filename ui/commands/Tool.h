// Инструменты окна чертежа.
#pragma once

namespace cosmocad::ui {

enum class Tool {
    Select,     // выбор щелчком и рамкой
    Line,       // отрезок по двум точкам, с продолжением
    Rectangle,  // прямоугольник по двум углам
    Circle,     // окружность: центр и точка (или радиус числом)
    Arc,        // дуга: центр, начало, конец (против часовой стрелки)
    Text,       // текст: точка вставки, затем окно ввода
    Dimension,  // линейный размер: две точки и положение размерной линии
    Radius,     // размер радиуса: щелчок по окружности или дуге, затем направление стрелки
    Diameter,   // размер диаметра: так же
    Leader,     // выноска: куда указывает стрелка, место излома, затем окно ввода текста
    Angle,      // угловой размер: вершина, точка на первой стороне, на второй, положение дуги
    Move,       // перенос выбранного: откуда и куда
    Copy,       // копия выбранного: откуда и куда
    Rotate,     // поворот выбранного: центр и направление (или угол числом, в градусах)
    Mirror,     // отражение выбранного: две точки оси
    Trim,       // обрезка: щелчок по лишней части отрезка
    Fillet,     // скругление: щелчки по двум отрезкам; радиус задаётся числом
    Chamfer,    // фаска: щелчки по двум отрезкам; размер задаётся числом
    SchElement, // элемент схемы: точка вставки
    SchWire,    // проводник схемы: точки по очереди, Esc — закончить
    SchLabel,   // метка цепи: точка, затем имя цепи
    Roughness,  // знак шероховатости: точка на линии, затем значение
};

}  // namespace cosmocad::ui
